const PQ_AXES = [
  { letters:['E','I'] },
  { letters:['S','N'] },
  { letters:['T','F'] },
  { letters:['J','P'] },
  { letters:['Assertive','Turbulent'] },
];

// A/B回答の集計から5軸を判定する。Cは加点しない。同数は判定なし（？）
function pqCompute(answers) {
  const tally = {};
  PQ_QUESTIONS.forEach(q => {
    const ans = answers[q.n];
    if (!ans || ans.choice === 'C') return;
    const letter = q.key[ans.choice];
    tally[letter] = (tally[letter] || 0) + 1;
  });
  const axisResults = PQ_AXES.map(axis => {
    const [l1, l2] = axis.letters;
    const c1 = tally[l1] || 0, c2 = tally[l2] || 0;
    const winner = c1 > c2 ? l1 : c2 > c1 ? l2 : null;
    return { l1, c1, l2, c2, winner };
  });
  const codeLetters = axisResults.slice(0, 4).map(a => a.winner || '？').join('');
  const atWinner = axisResults[4].winner;
  const atLetter = atWinner === 'Assertive' ? 'A' : atWinner === 'Turbulent' ? 'T' : '？';
  return { tally, axisResults, typeCode: codeLetters + '-' + atLetter };
}
